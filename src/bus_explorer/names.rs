#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_manufacturers() {
        assert_eq!(manufacturer_name(1851), Some("Raymarine"));
        assert_eq!(manufacturer_name(229), Some("Garmin"));
        assert_eq!(manufacturer_name(9999), None);
    }

    #[test]
    fn owner_bus_manufacturers() {
        for (code, name) in [
            (275, "Navico"),
            (381, "B & G"),
            (1857, "Simrad"),
            (273, "Actisense"),
            (717, "Yacht Devices"),
            (137, "Maretron"),
            (1855, "Furuno"),
        ] {
            assert_eq!(manufacturer_name(code), Some(name), "{code}");
        }
    }

    #[test]
    fn tables_are_sorted_for_binary_search() {
        assert!(MANUFACTURERS.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(DEVICE_CLASSES.windows(2).all(|w| w[0].0 < w[1].0));
    }

    #[test]
    fn device_classes_and_functions() {
        assert_eq!(device_class_name(25), Some("Internetwork device"));
        assert_eq!(device_class_name(60), Some("Navigation"));
        assert_eq!(device_class_name(99), None);
        assert_eq!(device_function_name(25, 130), Some("PC Gateway"));
        assert_eq!(device_function_name(40, 150), Some("Autopilot"));
        assert_eq!(
            device_function_name(60, 145),
            Some("Ownship Position (GNSS)")
        );
        assert_eq!(device_function_name(75, 130), Some("Temperature"));
        assert_eq!(device_function_name(85, 130), Some("Atmospheric"));
        assert_eq!(device_function_name(120, 130), Some("Display"));
        // Function numbers are class-scoped.
        assert_eq!(
            device_function_name(60, 150),
            Some("Ownship Position (Loran C)")
        );
        assert_eq!(device_function_name(30, 250), None);
    }

    #[test]
    fn pgn_names() {
        assert_eq!(pgn_name(127250), Some("Vessel Heading"));
        assert_eq!(pgn_name(60928), Some("ISO Address Claim"));
        assert_eq!(pgn_name(1), None);
    }
}
